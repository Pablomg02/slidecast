// Any language we ship wins on a prefix match; English is the fallback.
const NAV_LANG = String(navigator.language || 'en').toLowerCase();
export const lang = Object.keys(STRINGS).find((code) => code !== 'en' && NAV_LANG.startsWith(code)) ?? 'en';

export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}
